
from __future__ import annotations

import argparse
import json
import logging
from datetime import datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from bookml.data_loader.load_data import (
    ID_COLUMN,
    INVERSE_CATEGORY_MAP,
    LABEL_COLUMNS,
    TARGET_COLUMN,
    get_train_val_split,
    load_raw_data,
)
from sklearn.metrics import confusion_matrix
from bookml.evaluation.metrics import compute_classification_metrics, format_evaluation_report
from bookml.paths import BOOKS_CSV, DATA_DIR, OVERALL_CSV, PROJECT_ROOT, RESULTS_DIR, VAL_IDS_TXT
from bookml.registry import FEATURE_REGISTRY, MODEL_REGISTRY, build_model
from bookml.recipes import EXPERIMENTS

logger = logging.getLogger("bookml")


# =============================================================================
# PIPELINE
# =============================================================================
def apply_features(raw_df: pd.DataFrame, feature_keys: list[str]) -> pd.DataFrame:
    # Start with an empty DataFrame (no features at the beginning)
    features_df = pd.DataFrame(index=raw_df.index)
    context_df = raw_df.copy()

    for key in feature_keys:
        if key in FEATURE_REGISTRY:
            entry = FEATURE_REGISTRY[key]
            if isinstance(entry, str):
                features_df[entry] = context_df[entry]
                logger.info("Selected direct feature '%s' (column: '%s').", key, entry)
            elif callable(entry):
                logger.info("Applying feature function '%s' (%s)...", key, entry.__name__)
                result = entry(context_df)
                # Find new columns generated by the function
                new_cols = [c for c in result.columns if c not in context_df.columns]
                cols_to_add = result[new_cols] if new_cols else result
                for c in cols_to_add.columns:
                    features_df[c] = cols_to_add[c]
                    context_df[c] = cols_to_add[c]
        elif key in context_df.columns:
            features_df[key] = context_df[key]
            logger.info("Selected direct CSV column '%s'.", key)

    return features_df


def run_experiment(
    config: dict[str, Any],
) -> dict[str, Any]:

    logger.info("=" * 70)
    logger.info("EXPERIMENT: %s | model=%s | features=%s",
                config["name"], config["model"], config["features"])
    logger.info("=" * 70)

    # 1. Load raw data (adds `id` and `target`)
    raw_df = load_raw_data(BOOKS_CSV)

    # 2. Build feature matrix: starts with NO features, selecting ONLY requested ones
    features_df = apply_features(raw_df, config["features"])

    # 3. Train/validation split using fixed validation file
    train_raw, val_raw = get_train_val_split(raw_df, val_file=VAL_IDS_TXT)
    is_val = raw_df[ID_COLUMN].isin(val_raw[ID_COLUMN])

    X_train = features_df[~is_val].reset_index(drop=True)
    y_train = train_raw[TARGET_COLUMN].to_numpy()

    X_val = features_df[is_val].reset_index(drop=True)
    y_val = val_raw[TARGET_COLUMN].to_numpy()
    logger.info(
        "Train: %d rows (Fiction=%d, Nonfiction=%d) | Validation: %d rows (Fiction=%d, Nonfiction=%d)",
        len(y_train), (y_train == 1).sum(), (y_train == 0).sum(),
        len(y_val), (y_val == 1).sum(), (y_val == 0).sum(),
    )

    # 4. Build + train the requested model
    model = build_model(config["model"], **config.get("model_params", {}))
    logger.info("Training model '%s' (%s)...", config["model"], type(model).__name__)
    model.fit(X_train, y_train)

    best_params = getattr(model, "best_params_", {})
    cv_best_score = getattr(model, "best_score_", None)
    if cv_best_score is not None:
        logger.info("Best CV score: %.4f | Best params: %s", cv_best_score, best_params)

    # 5. Evaluate on the held-out validation set
    val_pred = model.predict(X_val)
    val_proba = model.predict_proba(X_val)[:, 1]

    metrics = compute_classification_metrics(y_val, val_pred, val_proba)
    logger.info("Validation metrics: %s",
                {k: (round(v, 4) if v is not None else None) for k, v in metrics.items()})
    logger.info("\n%s", format_evaluation_report(y_val, val_pred))

    predictions = pd.DataFrame({
        ID_COLUMN: val_raw[ID_COLUMN].to_numpy(),
        "title": val_raw["title"].to_numpy(),
        "actual": [INVERSE_CATEGORY_MAP[v] for v in y_val],
        "predicted": [INVERSE_CATEGORY_MAP[v] for v in val_pred]
    })

    top_features = model.feature_importances()

    # Calculate confusion matrix components (labels: [0=Nonfiction, 1=Fiction])
    tn, fp, fn, tp = confusion_matrix(y_val, val_pred, labels=[0, 1]).ravel()
    cm_dict = {
        "tp": int(tp),
        "tn": int(tn),
        "fp": int(fp),
        "fn": int(fn),
    }

    result = {
        "model": model,
        "metrics": metrics,
        "confusion_matrix": cm_dict,
        "best_params": best_params,
        "cv_best_score": cv_best_score,
        "predictions": predictions,
        "top_features": top_features,
    }

    # 6. Persist results
    _save_results(config, result)

    return result



def _save_results(config: dict[str, Any], result: dict[str, Any]) -> Path:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    path = RESULTS_DIR / f"{config['name']}.json"
    now_iso = datetime.now().isoformat(timespec="seconds")

    payload = {
        "experiment": config["name"],
        "timestamp": now_iso,
        "config": config,
        "cv_best_score": result["cv_best_score"],
        "best_params": result["best_params"],
        "validation_metrics": result["metrics"],
        "confusion_matrix": result.get("confusion_matrix"),
        "top_features": result["top_features"],
    }

    with open(path, "w", encoding="utf-8") as f:
        # default=str handles Paths and numpy scalars in params/config
        json.dump(payload, f, indent=2, ensure_ascii=False, default=str)
    logger.info("Results written to '%s'.", path)

    # Append summary row to overall.csv
    metrics = result.get("metrics") or {}
    csv_row = {
        "timestamp": now_iso,
        "experiment": config.get("name"),
        "model": config.get("model"),
        "features": json.dumps(config.get("features", [])),
        "cv_best_score": result.get("cv_best_score"),
        "accuracy": metrics.get("accuracy"),
        "precision": metrics.get("precision"),
        "recall": metrics.get("recall"),
        "f1": metrics.get("f1"),
        "roc_auc": metrics.get("roc_auc"),
        "best_params": json.dumps(result.get("best_params", {}), default=str),
    }

    row_df = pd.DataFrame([csv_row])
    row_df.to_csv(OVERALL_CSV, mode="a", header=False, index=False)
    logger.info("Summary appended to '%s'.", OVERALL_CSV)

    return path


# =============================================================================
# CLI
# =============================================================================
def main(argv: list[str] | None = None) -> None:

    parser = argparse.ArgumentParser(description="Run a registry-driven BookML experiment.")
    parser.add_argument(
        "--experiment",
        default="xgb_tfidf_baseline",
        choices=sorted(EXPERIMENTS),
        help="Named experiment config to run.",
    )
    args = parser.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="%(asctime)s | %(levelname)s | %(message)s")

    run_experiment(EXPERIMENTS[args.experiment])


if __name__ == "__main__":
    main()
